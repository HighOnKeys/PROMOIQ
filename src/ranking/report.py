"""Markdown editorial report for the content editor."""
from __future__ import annotations

from collections import Counter
from pathlib import Path


def write_report(path: Path, show, ranked, rejected, evals, meta, dup_log, alternatives=()) -> None:
    L = []
    L.append(f"# PROMOIQ editorial report: {show.title}\n")
    L.append(f"Generated by PROMOIQ ({meta['models']['generator']} generator, {meta['models']['judge']} judges, "
             f"{meta['models']['embeddings']} similarity).\n")
    L.append("> PROMOIQ reads screenplay text only. It cannot see the actual footage, the acting or the edit, "
             "and it has no audience data. Every cut point is a real screenplay timestamp and should be checked "
             "against the edited episode before publishing.\n")
    L.append("## Run summary\n")
    L.append(f"- Episodes analysed: **{meta['episodes']}** ({meta['runtime_s_total_footage'] / 60:.1f} min of footage, "
             f"{meta['events']} screenplay events, {meta['beats']} legal cut units)")
    L.append(f"- Candidates generated: **{meta['candidates']['total']}** ({meta['candidates']['continuous']} continuous, "
             f"{meta['candidates']['multi_segment']} multi-segment)")
    L.append(f"- Passed every hard check and editorial gate: **{meta['validated']}**; rejected: **{meta['rejected']}**")
    L.append(f"- Near-duplicates flagged during shortlisting: {meta['duplicates_flagged']}")
    L.append(f"- Wall-clock time: {meta['total_s']:.1f}s; LLM calls: {meta['usage']['generator'].get('calls', 0)}\n")
    L.append("## Post these first\n")
    L.append("Ranking = validated quality score Q with judge adjustments, then a diversity pass (MMR) so the "
             "shortlist covers different angles instead of ten cuts of the same scene.\n")
    L.append("| Rank | Promo | Theme | Segments | Duration | Q | Confidence |")
    L.append("|---|---|---|---|---|---|---|")
    for r in ranked:
        segs = "<br>".join(f"E{s['episode']} {s['start']} to {s['end']}" for s in r["segments"])
        L.append(f"| {r['rank']} | {r['promo_id']} | {r['theme']} | {segs} | {r['total_duration_s']:.1f}s | "
                 f"{r['scores']['quality']:.2f} | {r['confidence']} |")
    L.append("")
    for r in ranked:
        s = r["scores"]
        L.append(f"### {r['rank']}. {r['promo_id']}: {r['theme']} ({r['mode'].replace('_', '-')}, {r['total_duration_s']:.1f}s)\n")
        for seg in r["segments"]:
            L.append(f"- Segment {seg['order']}: Episode {seg['episode']}, {seg['start']} to {seg['end']} ({seg['duration_s']:.1f}s)")
        L.append(f"- **Hook (first 3s):** {r['hook']}")
        L.append(f"- **Cliffhanger:** {r['cliffhanger']}")
        L.append(f"- **Why it works:** {r['why_it_works']}")
        L.append(f"- Scores: H {s['hook']:.1f} · K {s['cliffhanger']:.1f} · C {s['clarity']:.1f} · E {s['emotion']:.1f} · "
                 f"G {s['info_gap']:.1f} · N {s['coherence']:.1f} · R {s['redundancy']:.1f} · S {s['spoiler']:.1f} → Q {s['quality']:.2f}")
        cv = r["cold_viewer"]
        L.append(f"- Cold-viewer check: standalone={cv['standalone']} (clarity {cv['clarity_score']:.1f}); open question: "
                 f"\"{cv['what_remains_unknown'][:120]}\"")
        if cv["missing_information"]:
            L.append(f"- Missing for a new viewer: {'; '.join(cv['missing_information'][:3])}")
        better = [x for x in r["boundary_counterfactuals"] if x.get("valid")]
        if better:
            L.append("- Boundary alternatives: " + "; ".join(f"{x['variant']} {x['start']}-{x['end']} Q {x['quality']:.2f} ({x['delta']:+.2f})" for x in better))
        L.append(f"- Confidence: {r['confidence']}. " + " ".join(r["limitations"]))
        L.append("")
    L.append("## Why the order\n")
    if ranked:
        top = ranked[0]
        L.append(f"- **{top['promo_id']} goes first** because it has the strongest combination of a hook a scroller "
                 f"cannot ignore (H {top['scores']['hook']:.1f}/10) and an ending that withholds the answer "
                 f"(K {top['scores']['cliffhanger']:.1f}/10), and it explains itself (C {top['scores']['clarity']:.1f}/10).")
        themes = Counter(r["theme"] for r in ranked)
        L.append(f"- The shortlist spans {len(themes)} angles ({', '.join(f'{t} x{n}' for t, n in themes.most_common())}), so promos can be "
                 "rotated or A/B tested against different audience interests.")
        L.append("- The diversity pass (MMR) decides which ten make the list; the order within it is by score. Scenes left out only "
                 "because they repeat a chosen angle are listed below as alternatives.")
    if alternatives:
        L.append("\n## Strong alternatives held back for diversity\n")
        L.append("These scored at least as well as the last shortlisted promo but repeat an angle already chosen. "
                 "Swap one in if you prefer it; the diversity rule is a judgment call, not a quality verdict.\n")
        for a in alternatives:
            segs = " + ".join(f"E{s['episode']} {s['start']}-{s['end']}" for s in a["segments"])
            L.append(f"- {a['candidate_id']} [{a['theme']}] {segs} ({a['duration_s']:.1f}s, score {a['final_score']:.2f}): "
                     f"{a['held_back_because']}")
    L.append("\n## Where the tool picks badly (rejections and flags)\n")
    reasons = Counter()
    examples = {}
    for c in rejected:
        for rs in evals[c.promo_id]["gate_failures"]:
            key = rs.split(" (")[0]
            reasons[key] += 1
            examples.setdefault(key, (c, rs))
    for key, n in reasons.most_common(8):
        c, rs = examples[key]
        segs = " + ".join(f"E{s.episode} {s.start_raw}-{s.end_raw}" for s in c.segments)
        L.append(f"- **{key}**: {n} candidates. Example {c.promo_id} ({segs}): {rs}")
    L.append("\nSee `evaluation/failure_analysis.md` for reviewed failure cases.\n")
    path.write_text("\n".join(L))
